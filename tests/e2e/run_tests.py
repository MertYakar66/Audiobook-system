    def test_performance_metrics(self):
        self.page.goto(f"{self.base_url}/web/library.html", wait_until="load")
        metrics = self.page.evaluate(
            """() => {
                const t = performance.timing || performance.getEntriesByType('navigation')[0];
                if (performance.getEntriesByType) {
                    const nav = performance.getEntriesByType('navigation')[0];
                    if (nav) return { domContentLoaded: nav.domContentLoadedEventEnd, load: nav.loadEventEnd, ttfb: nav.responseStart };
                }
                return { domContentLoaded: t.domContentLoadedEventEnd - t.navigationStart, load: t.loadEventEnd - t.navigationStart };
            }"""
        )
        return f"DCL={metrics.get('domContentLoaded',0):.0f}ms, load={metrics.get('load',0):.0f}ms, TTFB={metrics.get('ttfb',0):.0f}ms"

    def test_offline_static_cache(self):
        """Verify service worker caches static files by going offline and reloading."""
        # Prime the cache
        self.page.goto(f"{self.base_url}/web/library.html", wait_until="networkidle")
        self.page.wait_for_function(
            "() => navigator.serviceWorker && navigator.serviceWorker.controller !== null",
            timeout=5000,
        )
        self.context.set_offline(True)
        try:
            self.page.reload(wait_until="load", timeout=10000)
            self.page.wait_for_selector(".book-card", timeout=5000)
            title = self.page.title()
        finally:
            self.context.set_offline(False)
        return f"offline reload ok, title='{title}'"

