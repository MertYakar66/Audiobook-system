    def test_audio_text_sync(self):
        """Seek to known timing start and verify the correct .sentence.active."""
        entries = self.page.evaluate(
            "() => window.reader.timingData.chapters[0].entries.slice(0, 20)"
        )
        assert len(entries) >= 5, "need at least 5 timing entries"
        targets = [entries[0], entries[2], entries[4]]
        matched = 0
        details = []
        for entry in targets:
            mid = (entry["start"] + entry["end"]) / 2.0
            self.page.evaluate(
                f"() => {{ const a = document.getElementById('audio'); a.currentTime = {mid}; a.dispatchEvent(new Event('timeupdate')); }}"
            )
            try:
                self.page.wait_for_function(
                    f"""() => {{
                        const el = document.querySelector('.sentence.active');
                        return el && el.dataset.id === '{entry["id"]}';
                    }}""",
                    timeout=4000,
                )
                matched += 1
                details.append(f"t={mid:.2f}s→{entry['id']}")
            except PWTimeoutError:
                active = self.page.evaluate(
                    "() => { const el = document.querySelector('.sentence.active'); return el ? el.dataset.id : null; }"
                )
                details.append(f"t={mid:.2f}s expected={entry['id']} got={active} FAIL")
        assert matched == len(targets), "; ".join(details)
        return f"{matched}/{len(targets)} sync checks passed — " + "; ".join(details)

